const png = (svg) => "data:image/png;base64," + Buffer.from(new Resvg(svg, { fitTo: { mode: "width", value: 24 }, background: "rgba(0,0,0,0)" }).render().asPng()).toString("base64");
// Drawn 22 by 22 inside the 24 by 24 square, the one-pixel margin GitHub's mark-github-24 keeps on every side.
const mark = (ink) => png(`<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><svg x="1" y="1" width="22" height="22" viewBox="${MARK_VIEWBOX}"><path fill="${ink}" fill-rule="evenodd" d="${MARK_PATH}"/></svg></svg>`);
const lucide = (name, ink) => png(readFileSync(require.resolve(`lucide-static/icons/${name}.svg`), "utf8").replace(/stroke="currentColor"/, `stroke="${ink}"`));
const pair = (light, dark) => [{ src: light, mimeType: "image/png", theme: "light" }, { src: dark, mimeType: "image/png", theme: "dark" }];

const out = { server: pair(mark(LIGHT_INK), mark(DARK_INK)), groups: Object.fromEntries(Object.entries(GROUPS).map(([g, n]) => [g, pair(lucide(n, LIGHT_INK), lucide(n, DARK_INK))])) };
writeFileSync("src/mcp/icons.generated.ts", `// SPDX-License-Identifier: LicenseRef-Trooth-Proprietary
// Copyright (c) 2026 Trooth, LLC
// GENERATED by scripts/build-icons.mjs. Do not edit. The Trooth mark and the Lucide icons (ISC license) for each group.
export interface McpIcon { src: string; mimeType: "image/png"; theme: "light" | "dark" }
export const SERVER_ICONS: McpIcon[] = ${JSON.stringify(out.server)};
export const GROUP_ICONS: Record<string, McpIcon[]> = ${JSON.stringify(out.groups)};
export const GROUP_ICON_NAMES: Record<string, string> = ${JSON.stringify(GROUPS)};
`);
